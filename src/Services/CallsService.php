<?php

namespace NextDeveloper\CRM\Services;

use Illuminate\Contracts\Pagination\LengthAwarePaginator;
use Illuminate\Database\Eloquent\Collection;
use NextDeveloper\CRM\Database\Filters\CallsQueryFilter;
use NextDeveloper\CRM\Services\AbstractServices\AbstractCallsService;

/**
 * This class is responsible from managing the data for Calls
 *
 * Class CallsService.
 *
 * @package NextDeveloper\CRM\Database\Models
 */
class CallsService extends AbstractCallsService
{

    // EDIT AFTER HERE - WARNING: ABOVE THIS LINE MAY BE REGENERATED AND YOU MAY LOSE CODE
    /**
     * The generated create() never stamps iam_account_id, so logging a call failed on the NOT NULL column. The
     * account always comes from the acting account (an untrusted client cannot choose it), and the account /
     * opportunity the call is attached to must be visible to the caller.
     */
    public static function create(array $data)
    {
        \NextDeveloper\CRM\Helpers\TenantHelper::assertVisible(\NextDeveloper\CRM\Database\Models\Accounts::class, $data['crm_account_id'] ?? null);
        \NextDeveloper\CRM\Helpers\TenantHelper::assertVisible(\NextDeveloper\CRM\Database\Models\Opportunities::class, $data['crm_opportunity_id'] ?? null);

        if (!\NextDeveloper\IAM\Helpers\UserHelper::bypassRolesCheck() || empty($data['iam_account_id'])) {
            $data['iam_account_id'] = \NextDeveloper\IAM\Helpers\UserHelper::currentAccount()->id;
        }

        return parent::create($data);
    }

    public static function get(?CallsQueryFilter $filter = null, array $params = []): Collection|LengthAwarePaginator
    {
        return parent::get($filter, $params); // TODO: Change the autogenerated stub
    }
}
